def minutes(t: str) -> float:
    h, m = t.rstrip("m").split("h")
    return int(h) * 60 + int(m)


def pct(cli: float, gui: float) -> float:
    return (cli - gui) / gui * 100 if gui else 0.0


def fmt(v: float) -> str:
    return f"{v:.2f}"


def table_row(cells) -> str:
    return "| " + " | ".join(cells) + " |"


def render(tx: dict, rows, const_rows, failures) -> str:
    md = [tx["title"], "", tx["switch"], "", *tx["intro"], "", tx["h_main"], "",
          table_row(tx["cols"]), "|---" * len(tx["cols"]) + "|"]
    for d, cli, ref, diffs, ttext in rows:
        if d not in GUI:
            continue
        mark = "**" if d in REQUIRED else ""
        for key in ("total", "bridge", "sparse", "solid", "time"):
            gui_v, cli_v = (ref["time"], ttext) if key == "time" else (fmt(ref[key]), fmt(cli[key]))
            md.append(table_row([f"{mark}{d}%{mark}", tx["labels"][key], gui_v, cli_v, f"{diffs[key]:+.2f}%"]))
    md += ["", tx["h_total"], "", table_row(tx["cols_total"]), "|---" * len(tx["cols_total"]) + "|"]
    for d, cli, ref, diffs, _ in rows:
        if d in GUI_TOTAL_ONLY:
            md.append(table_row([f"{d}%", fmt(ref["total"]), fmt(cli["total"]), f"{diffs['total']:+.2f}%"]))
    md += ["", tx["h_const"], "", table_row([tx["density"], *GUI_CONSTANT]),
           "|---" * (len(GUI_CONSTANT) + 1) + "|", table_row(["GUI", *map(fmt, GUI_CONSTANT.values())])]
    for d, vals in const_rows:
        md.append(table_row([f"{d}%", *map(fmt, vals.values())]))
    md += ["", tx["h_notes"], "", *tx["notes"], "", tx["h_result"], "",
           tx["all_ok"] if not failures else tx["some_bad"] + tx["sep"].join(f"{d}%" for d in failures)]
    return "\n".join(md) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("model", type=Path)
    ap.add_argument("--plate", type=int, default=1)
    ap.add_argument("--out-dir", type=Path, default=Path("docs"))
    ap.add_argument("--work", type=Path, default=Path("work/verify"))
    a = ap.parse_args()

    a.work.mkdir(parents=True, exist_ok=True)
    model = a.work / "model.3mf"
    shutil.copyfile(a.model, model)  # never hand the original to the slicer

    rows, const_rows, failures = [], [], []
    for d in sorted(set(GUI) | set(GUI_TOTAL_ONLY)):
        run = slice_plate(model, a.plate, {"sparse_infill_density": f"{d}%"}, a.work / f"d{d}")
        s = read_sliced_3mf(run.output_3mf, a.plate, run.result_json)
        assert s.config["sparse_infill_density"] == f"{d}%", s.config
        g = s.feature_g
        cli = dict(sparse=g.get("Sparse infill", 0), bridge=g.get("Bridge", 0),
                   solid=g.get("Internal solid infill", 0), total=s.total_g,
                   time_min=s.total_time_s / 60)
        ref = GUI.get(d)
        if ref:
            diffs = {k: pct(cli[k], ref[k]) for k in ("sparse", "bridge", "solid", "total")}
            diffs["time"] = pct(cli["time_min"], minutes(ref["time"]))
            ok = all(abs(v) <= TOLERANCE * 100 for v in diffs.values())
        else:
            diffs = {"total": pct(cli["total"], GUI_TOTAL_ONLY[d])}
            ok = abs(diffs["total"]) <= TOLERANCE * 100
        if not ok:
            failures.append(d)
        rows.append((d, cli, ref or {"total": GUI_TOTAL_ONLY[d]}, diffs, s.total_time))
        const_rows.append((d, {k: g.get(k, 0) for k in GUI_CONSTANT}))
        try:
            run.output_3mf.unlink()
        except OSError:
            pass  # held by a slicer stuck in teardown; see docs/design.md
        print(f"{d:>3}%  total {s.total_g:7.2f} g  {'OK' if ok else 'DIFF'}")

    a.out_dir.mkdir(parents=True, exist_ok=True)
    for tx in TEXT.values():
        path = a.out_dir / tx["file"]
        path.write_text(render(tx, rows, const_rows, failures), encoding="utf-8")
        print(f"wrote {path}")
    print(f"failures: {failures or 'none'}")
    return 1 if any(d in REQUIRED for d in failures) else 0


if __name__ == "__main__":
    sys.exit(main())
